"""Build SUMMARY.md for one benchmark run directory, from the saved files only.

Usage: python scripts/summarize_benchmarks.py benchmarks/results/<timestamp>
Reports the median across runs and the min-max range, so variation is visible.
"""

from __future__ import annotations

import csv
import json
import re
import statistics
import sys
from collections import defaultdict
from pathlib import Path

RUN_RE = re.compile(r"^(?P<scenario>.+)-run(?P<run>\d+)$")


def median_range(values: list[float], fmt: str) -> str:
    if not values:
        return "n/a"
    med = statistics.median(values)
    if len(values) == 1:
        return fmt.format(med)
    return f"{fmt.format(med)} ({fmt.format(min(values))}-{fmt.format(max(values))})"


def k6_values(path: Path) -> dict[str, float]:
    m = json.loads(path.read_text())["metrics"]
    dur = m["http_req_duration"]["values"]
    out = {
        "rps": m["http_reqs"]["values"]["rate"],
        "requests": m["http_reqs"]["values"]["count"],
        "p50": dur["med"],
        "p95": dur["p(95)"],
        "p99": dur["p(99)"],
        "err": m["http_req_failed"]["values"]["rate"] * 100,
    }
    if "relay_cache_hits" in m or "relay_cache_misses" in m:
        hits = m.get("relay_cache_hits", {}).get("values", {}).get("count", 0)
        misses = m.get("relay_cache_misses", {}).get("values", {}).get("count", 0)
        out["hit_ratio"] = 100 * hits / max(1, hits + misses)
    if "allowed_200" in m:
        out["allowed"] = m["allowed_200"]["values"]["count"]
        out["limited"] = m.get("limited_429", {}).get("values", {}).get("count", 0)
    return out


def gateway_counters(txt: Path) -> dict[str, float]:
    match = re.search(r"GATEWAY_COUNTERS (\{.*?\})\"", txt.read_text().replace('\\"', '"'))
    return json.loads(match.group(1)) if match else {}


def _mem_mib(value: str) -> float:
    used = value.split("/")[0].strip()
    num = float(re.sub(r"[^\d.]", "", used))
    return num / 1024 if "KiB" in used else num * 1024 if "GiB" in used else num


def container_usage(stats: Path) -> dict[str, tuple[float, float]]:
    """container -> (median CPU %, max memory MiB) during the run."""
    cpu: dict[str, list[float]] = defaultdict(list)
    mem: dict[str, list[float]] = defaultdict(list)
    if not stats.exists():
        return {}
    with stats.open() as fh:
        for row in csv.reader(fh):
            if len(row) != 4:
                continue
            _, name, cpu_pct, mem_usage = row
            name = name.removeprefix("relay-").removesuffix("-1")
            try:
                cpu[name].append(float(cpu_pct.rstrip("%")))
                mem[name].append(_mem_mib(mem_usage))
            except ValueError:
                continue
    return {n: (statistics.median(cpu[n]), max(mem[n])) for n in cpu if cpu[n]}


def main(run_dir: Path) -> None:
    runs: dict[str, list[dict[str, float]]] = defaultdict(list)
    usage: dict[str, list[dict[str, tuple[float, float]]]] = defaultdict(list)
    counters: dict[str, list[dict[str, float]]] = defaultdict(list)
    for path in sorted(run_dir.glob("*.json")):
        match = RUN_RE.match(path.stem)
        if not match:
            continue
        scenario = match["scenario"]
        runs[scenario].append(k6_values(path))
        usage[scenario].append(container_usage(run_dir / f"{path.stem}.stats.csv"))
        txt = run_dir / f"{path.stem}.txt"
        if scenario.startswith("failure") and txt.exists():
            counters[scenario].append(gateway_counters(txt))

    env = (
        (run_dir / "environment.txt").read_text() if (run_dir / "environment.txt").exists() else ""
    )
    lines = [
        f"# Benchmark summary: {run_dir.name}",
        "",
        "Generated by `scripts/summarize_benchmarks.py` from the raw k6 JSON in this",
        "directory. Values are the **median across runs (min-max)**. Local laptop numbers,",
        "not production capacity claims.",
        "",
        "## Environment",
        "",
        "```text",
        env.strip(),
        "```",
        "",
        "## Throughput and latency",
        "",
        "| Scenario | Runs | Requests/s | p50 ms | p95 ms | p99 ms | Error % | Cache hit % |",
        "|---|---|---|---|---|---|---|---|",
    ]
    order = sorted(runs, key=lambda s: (s.split("-")[-1], s))
    for scenario in order:
        if scenario.startswith(("failure", "ratelimit")):
            continue
        rs = runs[scenario]
        hit = [r["hit_ratio"] for r in rs if "hit_ratio" in r]
        lines.append(
            f"| {scenario} | {len(rs)} | {median_range([r['rps'] for r in rs], '{:.0f}')} "
            f"| {median_range([r['p50'] for r in rs], '{:.2f}')} "
            f"| {median_range([r['p95'] for r in rs], '{:.2f}')} "
            f"| {median_range([r['p99'] for r in rs], '{:.2f}')} "
            f"| {median_range([r['err'] for r in rs], '{:.3f}')} "
            f"| {median_range(hit, '{:.1f}') if hit else '-'} |"
        )

    lines += [
        "",
        "## Container CPU / memory during each scenario",
        "",
        "Median CPU % (100% = one core) and peak memory, sampled about once per second",
        "with `docker stats`, then the median across runs.",
        "",
        "| Scenario | relay CPU % | relay peak MiB | backend-a CPU % | k6 CPU % |",
        "|---|---|---|---|---|",
    ]
    for scenario in order:
        per_run = [u for u in usage[scenario] if u]
        if not per_run:
            continue

        def pick(container: str, idx: int, per_run=per_run) -> list[float]:
            return [u[container][idx] for u in per_run if container in u]

        k6_cpu = [
            max((v[0] for k, v in u.items() if k.startswith("k6-run")), default=0) for u in per_run
        ]
        lines.append(
            f"| {scenario} | {median_range(pick('relay', 0), '{:.0f}')} "
            f"| {median_range(pick('relay', 1), '{:.0f}')} "
            f"| {median_range(pick('backend-a', 0), '{:.0f}')} "
            f"| {median_range(k6_cpu, '{:.0f}')} |"
        )

    for scenario in sorted(s for s in runs if s.startswith("failure")):
        rs, cs = runs[scenario], counters[scenario]
        lines += [
            "",
            "## Failure injection (backend-b returns 503 and fails health checks for 30 s)",
            "",
            "| Metric | Median (min-max) |",
            "|---|---|",
            f"| Requests/s | {median_range([r['rps'] for r in rs], '{:.0f}')} |",
            f"| p95 / p99 ms | {median_range([r['p95'] for r in rs], '{:.2f}')} / "
            f"{median_range([r['p99'] for r in rs], '{:.2f}')} |",
            f"| Client-visible error % | {median_range([r['err'] for r in rs], '{:.3f}')} |",
        ]
        for key in sorted({k for c in cs for k in c}):
            lines.append(
                f"| {key} (gateway) | {median_range([c.get(key, 0) for c in cs], '{:.0f}')} |"
            )

    for scenario in sorted(s for s in runs if s.startswith("ratelimit")):
        rs = runs[scenario]
        lines += [
            "",
            "## Distributed rate limit across two gateway instances",
            "",
            "One client alternates between `relay` and `relay-2` on `/api/orders`",
            "(capacity 5, refill 1/s) for 30 s. Ceiling = 5 + 1 x 30 = 35 allowed, plus",
            "1 token of tolerance for k6's sub-second graceful stop.",
            "",
            "| Run | Allowed (200) | Limited (429) | Within ceiling |",
            "|---|---|---|---|",
        ]
        for i, r in enumerate(rs, 1):
            ok = "yes" if r["allowed"] <= 36 else "NO"
            lines.append(f"| {i} | {r['allowed']:.0f} | {r['limited']:.0f} | {ok} |")

    (run_dir / "SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
